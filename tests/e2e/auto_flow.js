const { chromium } = require('playwright');
const SP = process.argv[2];
(async () => {
  const browser = await chromium.launch();
  const page = await browser.newPage({ viewport: { width: 1400, height: 1000 } });
  const errors = [];
  page.on('pageerror', e => errors.push('pageerror: ' + e.message));
  page.on('console', m => { if (m.type() === 'error') errors.push('console: ' + m.text()); });
  page.on('dialog', d => d.accept());
  await page.goto('http://localhost:8765/');
  await page.waitForSelector('#auto-form');
  await page.screenshot({ path: SP + '/a1-list.png' });
  await page.setInputFiles('#auto-file', require('path').join(__dirname, '../../examples/eval/sonda-kaucja.m4a'));
  await page.click('#auto-form button[type=submit]');
  await page.waitForSelector('.stages');
  await page.screenshot({ path: SP + '/a2-processing.png' });
  await page.waitForSelector('.tabs', { timeout: 300000 });
  await page.screenshot({ path: SP + '/a3-done.png', fullPage: true });
  const status = await page.textContent('.badge');
  console.log('STATUS', status, 'URL', page.url());
  await page.click('[data-seek="12"]').catch(e => errors.push('seek: ' + e.message));
  const t = await page.evaluate(() => document.getElementById('player')?.currentTime);
  console.log('player time', t);
  await page.click('#auto-run');
  await page.waitForSelector('.tabs', { timeout: 120000 });
  await page.goto('http://localhost:8765/#/');
  await page.waitForSelector('tr[data-id]');
  await page.screenshot({ path: SP + '/a4-list.png' });
  console.log('ERRORS:', JSON.stringify(errors));
  await browser.close();
})().catch(e => { console.error('FAIL', e); process.exit(1); });
