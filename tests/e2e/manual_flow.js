const { chromium } = require('playwright');
const SP = process.argv[2];
(async () => {
  const browser = await chromium.launch();
  const page = await browser.newPage({ viewport: { width: 1400, height: 1000 } });
  const errors = [];
  page.on('pageerror', e => errors.push('pageerror: ' + e.message));
  page.on('console', m => { if (m.type() === 'error') errors.push('console: ' + m.text()); });
  page.on('dialog', d => d.accept());
  await page.goto('http://localhost:8765/');
  await page.click('#demo');
  await page.waitForSelector('#analyze');
  await page.screenshot({ path: SP + '/1-empty.png' });
  await page.click('#analyze');
  await page.waitForSelector('#to-draft');
  await page.screenshot({ path: SP + '/2-evidence.png', fullPage: true });
  await page.click('#to-draft');
  await page.click('#generate');
  await page.waitForSelector('#draft-form');
  await page.screenshot({ path: SP + '/3-draft.png', fullPage: true });
  // dopisz zmyślony cytat
  const ta = page.locator('#lead');
  await ta.fill((await ta.inputValue()) + ' Ktoś: „Kaucja to najgorszy pomysł tego rządu”.');
  await page.click('#draft-form button[type=submit]');
  await page.waitForSelector('.verify.err');
  await page.screenshot({ path: SP + '/4-failed.png' });
  const ta2 = page.locator('#lead');
  await ta2.fill((await ta2.inputValue()).split(' Ktoś:')[0]);
  await page.click('#draft-form button[type=submit]');
  await page.waitForSelector('.verify.ok');
  await page.click('#approve');
  await page.waitForSelector('text=Zatwierdzony ✓');
  await page.click('[data-tab=export]');
  await page.waitForFunction(() => document.querySelector('#out')?.textContent.includes('## Lead'));
  await page.screenshot({ path: SP + '/5-export.png', fullPage: true });
  await page.click('[data-goto]').catch(()=>{});
  await page.goto('http://localhost:8765/#/styles');
  await page.fill('#pname', 'Test');
  await page.fill('#particles', 'Tytuł jeden\n\nLead pierwszy.\n\nAkapit.\n---\nTytuł dwa długi\n\nLead drugi.\n\nAkapit drugi.');
  await page.click('#new-profile button[type=submit]');
  await page.waitForSelector('form[data-profile]');
  await page.click('form[data-profile] summary');
  await page.screenshot({ path: SP + '/6-styles.png', fullPage: true });
  await page.goto('http://localhost:8765/#/');
  await page.waitForSelector('tr[data-id]');
  await page.screenshot({ path: SP + '/7-list.png' });
  await page.setViewportSize({ width: 390, height: 844 });
  await page.click('tr[data-id]');
  await page.waitForSelector('.tabs');
  await page.screenshot({ path: SP + '/8-mobile.png' });
  console.log('ERRORS:', JSON.stringify(errors));
  await browser.close();
})().catch(e => { console.error('FAIL', e); process.exit(1); });
